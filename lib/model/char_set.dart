/// 小書きの字。書き取り枠を小さくして書かせる（[smallKanaScale]）。
///
/// 拗音「きゃ」促音「がっこう」に要る。大きい や と同じ大きさで書くと、
/// フォントに載せたときに見分けが付かない。
bool isSmallKana(String char) => _smallKana.contains(char);

const _smallKana = {
  'ぁ', 'ぃ', 'ぅ', 'ぇ', 'ぉ', 'っ', 'ゃ', 'ゅ', 'ょ', //
  'ァ', 'ィ', 'ゥ', 'ェ', 'ォ', 'ッ', 'ャ', 'ュ', 'ョ', //
};

/// 小書きの字を書く枠の一辺。全角の枠に対する比。
///
/// 実測で決めた。ヒラギノ角ゴ W3 の ぁっゃゅょァ は大きい字の 0.81 倍、
/// KanjiVG の同じ字は 0.79〜0.80 倍。独立した 2 つの出典が一致する。
/// 枠は左右中央・下揃えに置く（どちらの出典も下端が大きい字とほぼ揃う）。
const smallKanaScale = 0.81;

/// 文字から所属する CharSet を引く。どこにも属さない文字は null。
CharSet? charSetOf(String char) {
  for (final set in CharSet.values) {
    if (set.chars.contains(char)) return set;
  }
  return null;
}

/// 読み上げるときの読み。かなは字面がそのまま読みになる。
///
/// 字面のままでは読めない字だけ明示する。「0」を「れい」と読むエンジンが
/// あるが、幼児に通じるのは「ゼロ」のほう。
///
/// カタカナは清音と読みが同じで、声だけでは「ア」と「あ」を区別できない。
/// 何も見ずに書くモードは音しか頼りがないため、文字種を頭に付けて呼ぶ。
/// 小書きも同じ理由で「ちいさい や」と呼ぶ。
String readingOf(String char) {
  final reading = _readings[char] ?? char;
  return charSetOf(char) == CharSet.katakana
      ? 'カタカナの $reading'
      : reading;
}

